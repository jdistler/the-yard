#!/usr/bin/env python3
"""Turn files into C arrays, so the runtime carries its font and its Lua library inside the
binary and cannot lose them. The outputs are committed (the cabinet's Docker toolchain has no
Python); test.py checks they are fresh.

    python3 tools/bin2c.py            regenerate engine/fonts/round_ttf.h and engine/lib_lua.h
    python3 tools/bin2c.py --check    exit 1 if either is stale
"""
import os
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ENGINE = os.path.join(HERE, "engine")


def array(name, data):
    lines = [f"static const unsigned char {name}[{len(data)}] = {{"]
    for i in range(0, len(data), 20):
        lines.append("    " + ",".join(str(b) for b in data[i:i + 20]) + ",")
    lines.append("};")
    return "\n".join(lines) + "\n"


def font_header():
    data = open(os.path.join(ENGINE, "fonts", "Fredoka-SemiBold.ttf"), "rb").read()
    return ("/* Generated by tools/bin2c.py from fonts/Fredoka-SemiBold.ttf (SIL OFL 1.1, fonts/Fredoka-OFL.txt).\n"
            " * Do not edit. */\n" + array("round_ttf", data))


def lib_header():
    libdir = os.path.join(ENGINE, "lib")
    names = sorted(n for n in os.listdir(libdir) if n.endswith(".lua"))
    out = ["/* Generated by tools/bin2c.py from the files in engine/lib. Do not edit; edit the .lua files. */"]
    table = []
    for n in names:
        sym = "lib_" + n[:-4]
        out.append(array(sym, open(os.path.join(libdir, n), "rb").read()))
        table.append(f'    {{"{n[:-4]}", {sym}, sizeof {sym}}},')
    out.append("static const struct { const char *name; const unsigned char *src; unsigned len; } lib_files[] = {")
    out += table
    out.append("};")
    return "\n".join(out) + "\n"


def main():
    targets = {os.path.join(ENGINE, "fonts", "round_ttf.h"): font_header(),
               os.path.join(ENGINE, "lib_lua.h"): lib_header()}
    stale = []
    for path, text in targets.items():
        old = open(path).read() if os.path.exists(path) else None
        if old != text:
            stale.append(path)
            if "--check" not in sys.argv:
                open(path, "w").write(text)
    if "--check" in sys.argv:
        for p in stale:
            print(f"stale: {os.path.relpath(p, HERE)} (run python3 tools/bin2c.py)")
        sys.exit(1 if stale else 0)
    for p in stale:
        print(f"wrote {os.path.relpath(p, HERE)}")


if __name__ == "__main__":
    main()
