#!/usr/bin/env bash
# Build the Shelf's libretro cores for the cabinet's RetroArch 1.7.4 (armhf, glibc <= 2.29, Cortex-A7 NEON).
# Sources are cloned to ~/partycade-build/src (outside git); the .so files land in ~/partycade-build/cores and
# go to the card's library/cores. Each core is gated by games/check_binary.sh.
#   games/shelf/build_cores.sh [core ...]      default: all of them
set -euo pipefail
HERE=$(cd "$(dirname "$0")" && pwd)
SRC=${SRC:-$HOME/partycade-build/src}
OUT=${OUT:-$HOME/partycade-build/cores}
mkdir -p "$SRC" "$OUT"
docker image inspect partycade-cores >/dev/null 2>&1 || docker build -q -t partycade-cores -f "$HERE/Dockerfile.cores" "$HERE"

# name  repo  make-args  built-file
CORES=(
  "fceumm|libretro-fceumm|-f Makefile.libretro platform=rpi2|fceumm_libretro.so"
  "gambatte|gambatte-libretro|-f Makefile.libretro platform=unix|gambatte_libretro.so"
  "ngp|beetle-ngp-libretro|platform=unix|mednafen_ngp_libretro.so"
  "pce|beetle-pce-fast-libretro|platform=unix|mednafen_pce_fast_libretro.so"
  "gpsp|gpsp|platform=rpi2|gpsp_libretro.so"
  "snes9x2005|snes9x2005|platform=unix USE_BLARGG_APU=0|snes9x2005_libretro.so"
  "snes9x2010|snes9x2010|platform=unix|snes9x2010_libretro.so"
  "picodrive|picodrive|-f Makefile.libretro platform=rpi2|picodrive_libretro.so"
)
want=" ${*:-all} "
A7="-mcpu=cortex-a7 -mfpu=neon-vfpv4 -mfloat-abi=hard -marm -O2"
fails=()
for c in "${CORES[@]}"; do
  IFS='|' read -r name repo args file <<<"$c"
  [[ "$want" == " all " || "$want" == *" $name "* ]] || continue
  [ -d "$SRC/$repo" ] || git clone -q --depth 1 "https://github.com/libretro/$repo.git" "$SRC/$repo"
  echo "== $name ($(git -C "$SRC/$repo" rev-parse --short HEAD))"
  docker run --rm -u "$(id -u):$(id -g)" -v "$SRC/$repo:/src" -w /src partycade-cores sh -c "
    make $args clean >/dev/null 2>&1 || true
    # PicoDrive's 68000 core is generated by a host program: build it natively before cross make sees it.
    [ -d cpu/cyclone ] && CFLAGS=-O2 CXXFLAGS=-O2 make -C cpu/cyclone CONFIG_FILE=../cyclone_config.h >/dev/null
    export CFLAGS='$A7' CXXFLAGS='$A7' LDFLAGS='-static-libstdc++ -static-libgcc'
    make -j\$(nproc) $args CC=arm-linux-gnueabihf-gcc CXX=arm-linux-gnueabihf-g++ AR=arm-linux-gnueabihf-ar \
      >/tmp/build.log 2>&1 || { grep -m5 -i error /tmp/build.log; tail -8 /tmp/build.log; exit 1; }
    arm-linux-gnueabihf-strip $file" || { fails+=("$name"); continue; }
  cp "$SRC/$repo/$file" "$OUT/$file"
  "$HERE/../check_binary.sh" "$OUT/$file"
  git -C "$SRC/$repo" rev-parse HEAD > "$OUT/$file.commit"
done
[ ${#fails[@]} = 0 ] || { echo "failed: ${fails[*]}"; exit 1; }
